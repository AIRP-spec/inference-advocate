#!/usr/bin/env python3
"""Regenerate spec/primitives.json, spec/classes.json and CLASSES.md from the
source files, copying definition strings verbatim.

Deliberately NOT copied: vocabulary.json `examples` and flags.v0.json
`criteria`/`counterExamples`. Both contain text that also appears in the v2
held-out suite (tools/check_no_protected.py flags them), so they must not enter v3/.

  python3 tools/extract_definitions.py VOCABULARY_JSON FLAGS_JSON
Sources (repo paths): tools/evaluator-training/primitives/vocabulary.json (branch
decide/shared-adopt) and data/taxonomy/flags.v0.json (main). Pins are enforced.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from airp_v3.fingerprint import sha256_file  # noqa: E402

PIN_VOCAB = "329171161e510d604fbaa05db53f42fe05a4b075a298684ef5c394b1c2a0342b"
PIN_FLAGS = "0de1cacc74cbdf0452e3785b37ccf00bf6f65683e0b448983c2330fb9c1729b1"
PIN_COMP = "59ddf1f630ec2dcd81d40dd01f2adb53f1310fe42128d3ccc9b90de61e28ab9e"


def main(vocab_path, flags_path):
    comp_path = ROOT / "spec" / "composition-2a.json"
    for p, pin in ((vocab_path, PIN_VOCAB), (flags_path, PIN_FLAGS), (comp_path, PIN_COMP)):
        got = sha256_file(p)
        if got != pin:
            sys.exit(f"{p}: sha256 {got} != pin {pin}")
    vocab = json.loads(Path(vocab_path).read_text("utf-8"))
    flags = json.loads(Path(flags_path).read_text("utf-8"))
    comp = json.loads(comp_path.read_text("utf-8"))

    prims = {
        "source": {"file": "tools/evaluator-training/primitives/vocabulary.json", "sha256": PIN_VOCAB,
                   "vocabularyVersion": vocab["vocabularyVersion"]},
        "omitted": "examples (overlap the v2 held-out suite); maps_to_kinds (training-recipe internals)",
        "structure": vocab["structure"],
        "stance": [{"primitive": x["primitive"], "definition": x["definition"]} for x in vocab["primitives"]["stance"]],
        "objects": [{"primitive": x["primitive"], "definition": x["definition"]} for x in vocab["primitives"]["object"]],
        "qualifiers": [{"primitive": x["primitive"], "definition": x["definition"]} for x in vocab["primitives"]["qualifiers"]],
    }
    rules = {c["class"]: c for c in comp["classes"]}
    classes = {
        "source": {"taxonomy": {"file": "data/taxonomy/flags.v0.json", "sha256": PIN_FLAGS,
                                "taxonomyVersion": flags["taxonomyVersion"]},
                   "composition": {"file": "spec/composition-2a.json", "sha256": PIN_COMP,
                                   "compositionVersion": comp["compositionVersion"]}},
        "omitted": "flags.v0.json criteria (lexical rule-evaluator patterns) and counterExamples (overlap the v2 held-out suite)",
        "classes": [{"type": f["type"], "title": f["title"], "definition": f["definition"], "severity": f["severity"],
                     "compositionDefinition": rules[f["type"]].get("definition"),
                     "compositionRule": rules[f["type"]]["rule"]} for f in flags["flags"]],
    }
    (ROOT / "spec" / "primitives.json").write_text(json.dumps(prims, indent=2) + "\n", "utf-8")
    (ROOT / "spec" / "classes.json").write_text(json.dumps(classes, indent=2) + "\n", "utf-8")

    def cond(c):
        if "allOf" in c:
            return "(" + " AND ".join(cond(x) for x in c["allOf"]) + ")"
        if "anyOf" in c:
            return "(" + " OR ".join(cond(x) for x in c["anyOf"]) + ")"
        parts = []
        if "stance" in c:
            parts.append(f"stance={c['stance']}")
        parts += [f"object:{o}" for o in c.get("objects", [])]
        parts += [f"qualifier:{q}" for q in c.get("qualifiers", [])]
        if not parts:
            return "TRUE"
        return parts[0] if len(parts) == 1 else "(" + " AND ".join(parts) + ")"

    md = ["# CLASSES: the 11 AIRP v0.5.0 classes and how composition 2a derives them", "",
          "Generated by `tools/extract_definitions.py`; do not edit by hand. Definitions are copied verbatim.", "",
          f"- Taxonomy: `data/taxonomy/flags.v0.json` sha256 `{PIN_FLAGS}` (`taxonomyVersion` {flags['taxonomyVersion']}). "
          "Columns *title*, *definition*, *severity*.",
          f"- Composition: `spec/composition-2a.json` sha256 `{PIN_COMP}` (`compositionVersion` {comp['compositionVersion']}), "
          "a verbatim copy of `tools/evaluator-training/primitives/compositions/airp-v0.5.0-cse-corrected-2a.json`. "
          "Column *rule* is a plain rendering of its `rule` field.",
          "- Not copied: `criteria` (lexical patterns of the rule evaluator) and `counterExamples`, because the "
          "counter-examples overlap v2 held-out text.", "",
          "Negative rule (applies before any class): if `qualifier:is_mention_not_use` fires AND `stance=describes`, "
          "no class fires. With any other stance the qualifier is ignored.", "",
          "| class | title | severity | definition (flags.v0.json) | rule (composition 2a) |",
          "|---|---|---|---|---|"]
    for c in classes["classes"]:
        md.append(f"| `{c['type']}` | {c['title']} | {c['severity']} | {c['definition']} | {cond(c['compositionRule'])} |")
    diff = [c for c in classes["classes"] if c["compositionDefinition"] != c["definition"]]
    md += ["", "Composition-file definitions that differ from flags.v0.json (both verbatim):" if diff
           else "Every composition-file `definition` string is identical to the flags.v0.json definition.", ""]
    for c in diff:
        md += [f"- `{c['type']}`: flags.v0.json: \"{c['definition']}\" / composition: \"{c['compositionDefinition']}\""]
    (ROOT / "CLASSES.md").write_text("\n".join(md) + "\n", "utf-8")
    print("wrote spec/primitives.json spec/classes.json CLASSES.md;", len(diff), "definition differences")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
